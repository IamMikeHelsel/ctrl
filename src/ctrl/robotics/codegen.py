@lean_theorem(
    "Research.RobotEnergySmoothness",
    ("qProfile", "vProfile", "aProfile", "jProfile", "exact_integral_quadratic_forms"),
    domain="codegen",
    summary="Emit deterministic C99 and IEC 61131-3 Structured Text sources for verified robotics kernels.",
)
def emit_c99_and_iec61131(output_dir: Path) -> dict[str, Path]:
    """Write ``ctrl_robotics_kernels.h``, ``.c``, and ``.st`` into ``output_dir``."""
    output_dir.mkdir(parents=True, exist_ok=True)
    h_path = output_dir / "ctrl_robotics_kernels.h"
    c_path = output_dir / "ctrl_robotics_kernels.c"
    st_path = output_dir / "ctrl_robotics_kernels.st"
    h_path.write_text(C99_HEADER, encoding="utf-8")
    c_path.write_text(C99_SOURCE, encoding="utf-8")
    st_path.write_text(IEC_61131_ST_SOURCE, encoding="utf-8")
    return {"header": h_path, "c_source": c_path, "st_source": st_path}


@lean_theorem(
    "Research.LorentzConeCBF",
    ("quad_contact_net_force", "quad_contact_zero_angular_momentum", "lorentz_backup_controller_safe"),
    domain="codegen",
    summary="Compile generated C99 kernels with clang -O3 and verify parity against Python reference.",
)
def compile_and_verify_c99_kernels() -> dict[str, Any]:
    """Compile C99 kernels into a shared library and run bit-accuracy checks via ctypes."""
    from ctrl.robotics.contact_cbf import (
        CentroidalQuadParams,
        lorentz_cbf_safety_filter,
        quad_contact_forces,
    )
    from ctrl.robotics.estimation_lqr import (
        backstepping_and_sontag_clf,
        kalata_alpha_beta_gains,
    )
    from ctrl.robotics.kinematics_ik import minimal_intervention_ik
    from ctrl.robotics.trajectories import (
        septic_a,
        septic_accel_integral,
        septic_j,
        septic_q,
        septic_v,
        septic_velocity_integral,
    )

    with tempfile.TemporaryDirectory() as tmp:
        tmp_dir = Path(tmp)
        paths = emit_c99_and_iec61131(tmp_dir)
        so_path = tmp_dir / "libctrl_robotics.dylib"
        cmd = [
            "clang",
            "-std=c99",
            "-O3",
            "-Wall",
            "-Wextra",
            "-Werror",
            "-shared",
            "-fPIC",
            str(paths["c_source"]),
            "-o",
            str(so_path),
            "-lm",
        ]
        subprocess.run(cmd, check=True, capture_output=True, text=True)

        lib = ctypes.CDLL(str(so_path))

        for fn_name in (
            "ctrl_septic_q",
            "ctrl_septic_v",
            "ctrl_septic_a",
            "ctrl_septic_j",
        ):
            fn = getattr(lib, fn_name)
            fn.argtypes = [ctypes.c_double, ctypes.c_double]
            fn.restype = ctypes.c_double

        for fn_name in ("ctrl_septic_ia", "ctrl_septic_iv"):
            fn = getattr(lib, fn_name)
            fn.argtypes = [ctypes.c_double]
            fn.restype = ctypes.c_double

        d3 = ctypes.c_double * 3
        lib.ctrl_quad_contact_force.argtypes = [
            ctypes.c_double,
            ctypes.c_double,
            ctypes.c_double,
            ctypes.c_double,
            ctypes.c_double,
            ctypes.c_double,
            ctypes.c_double,
            ctypes.c_double,
            ctypes.c_double,
            d3,
        ]
        lib.ctrl_quad_contact_force.restype = None

        lib.ctrl_lorentz_cbf_filter.argtypes = [d3, ctypes.c_double, d3, d3, d3]
        lib.ctrl_lorentz_cbf_filter.restype = ctypes.c_double

        lib.ctrl_minimal_intervention_ik.argtypes = [d3, d3, ctypes.c_double, d3]
        lib.ctrl_minimal_intervention_ik.restype = None

        lib.ctrl_kalata_alpha_beta.argtypes = [
            ctypes.c_double,
            ctypes.c_double,
            ctypes.c_double,
            ctypes.POINTER(ctypes.c_double),
            ctypes.POINTER(ctypes.c_double),
        ]
        lib.ctrl_kalata_alpha_beta.restype = None

        lib.ctrl_sontag_clf.argtypes = [ctypes.c_double, ctypes.c_double]
        lib.ctrl_sontag_clf.restype = ctypes.c_double

        lib.ctrl_backstepping_control.argtypes = [
            ctypes.c_double,
            ctypes.c_double,
            ctypes.c_double,
            ctypes.c_double,
            ctypes.c_double,
            ctypes.c_double,
            ctypes.c_double,
        ]
        lib.ctrl_backstepping_control.restype = ctypes.c_double

        max_err = 0.0
        for eta in (-11.0, -5.5, 0.0):
            max_err = max(max_err, abs(lib.ctrl_septic_ia(eta) - float(septic_accel_integral(eta))))
            max_err = max(max_err, abs(lib.ctrl_septic_iv(eta) - float(septic_velocity_integral(eta))))
            for s in (0.0, 0.25, 0.5, 0.75, 1.0):
                max_err = max(max_err, abs(lib.ctrl_septic_q(eta, s) - float(septic_q(eta, s))))
                max_err = max(max_err, abs(lib.ctrl_septic_v(eta, s) - float(septic_v(eta, s))))
                max_err = max(max_err, abs(lib.ctrl_septic_a(eta, s) - float(septic_a(eta, s))))
                max_err = max(max_err, abs(lib.ctrl_septic_j(eta, s) - float(septic_j(eta, s))))

        p = CentroidalQuadParams(m=40.0, g=9.81, h_g=0.45, w_x=0.25, w_y=0.18, mu=0.6)
        py_forces = quad_contact_forces(p, -2.5, 1.1)
        out_f = d3()
        for (ex_i, ey_i), f_py in py_forces.items():
            lib.ctrl_quad_contact_force(
                p.m, p.g, p.h_g, p.w_x, p.w_y, -2.5, 1.1, float(ex_i), float(ey_i), out_f
            )
            for k in range(3):
                max_err = max(max_err, abs(out_f[k] - f_py[k]))

        a_cbf = (-1.0, 0.0, 0.0)
        u_nom = (1.5, 0.4, 9.81)
        pi_b = (-4.5, 0.0, 9.81)
        lam_py, u_py = lorentz_cbf_safety_filter(a_cbf, 2.0, u_nom, pi_b)
        out_u = d3()
        lam_c = lib.ctrl_lorentz_cbf_filter(d3(*a_cbf), 2.0, d3(*u_nom), d3(*pi_b), out_u)
        max_err = max(max_err, abs(lam_c - lam_py))
        for k in range(3):
            max_err = max(max_err, abs(out_u[k] - u_py[k]))

        j_row = (1.0, 2.0, -2.0)
        q_nom = (0.3, -0.5, 0.75)
        q_py = minimal_intervention_ik(j_row, q_nom, 2.5)
        out_q = d3()
        lib.ctrl_minimal_intervention_ik(d3(*j_row), d3(*q_nom), 2.5, out_q)
        for k in range(3):
            max_err = max(max_err, abs(out_q[k] - q_py[k]))

        kal_py = kalata_alpha_beta_gains(0.05, 4.0, 0.01)
        c_alpha = ctypes.c_double()
        c_beta = ctypes.c_double()
        lib.ctrl_kalata_alpha_beta(0.05, 4.0, 0.01, ctypes.byref(c_alpha), ctypes.byref(c_beta))
        max_err = max(max_err, abs(c_alpha.value - kal_py["alpha"]))
        max_err = max(max_err, abs(c_beta.value - kal_py["beta"]))

        for a_val, b_val in ((1.2, 0.8), (-0.5, 1.5), (-1.0, 0.0), (0.0, -0.7)):
            clf_py = backstepping_and_sontag_clf(
                2.5, 3.0, 0.4, -0.2, 0.7, 0.6, -0.3, a_val, b_val
            )
            u_sontag_c = lib.ctrl_sontag_clf(a_val, b_val)
            u_bs_c = lib.ctrl_backstepping_control(2.5, 3.0, 0.4, -0.2, 0.7, 0.6, -0.3)
            max_err = max(max_err, abs(u_sontag_c - float(clf_py["u_sontag"])))
            max_err = max(max_err, abs(u_bs_c - float(clf_py["u_backstepping"])))

    return {
        "compiled_ok": True,
        "max_c99_vs_python_error": max_err,
        "parity_verified": max_err < 1e-12,
    }
